//! `brdf.slang`'s energy fit (`shaders/common/brdf_energy_fit.slang`): a spline fitted to a GPU bake of the lobe it
//! compensates, evaluated as the shaders evaluate it, and held to BeschleunigerBallett's furnace quadrature.
//! `KATAGLYPHIS_UPDATE_BRDF_ENERGY=1` refits it from a fresh bake; then regenerate the WGSL
//! (`compile-slang-shaders.sh`) and the vectors (`python3 scripts/generate-shader-vectors.py`), which read the fit.

use std::f64::consts::PI;

use glam::DVec3;
use kataglyphis_webgpu_renderer::GpuContext;
use wgpu::util::DeviceExt as _;

mod common;

const BAKE_WGSL: &str = include_str!("../src/shaders/brdf_energy_bake.wgsl");
/// Where the fit is checked in, for `KATAGLYPHIS_UPDATE_BRDF_ENERGY`.
const FIT_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../shaders/common/brdf_energy_fit.slang"
);
/// `brdf_energy_bake.slang`'s invocations per probe and samples per probe (`BAKE_ROWS * BAKE_COLUMNS`).
const BAKE_CHUNKS: usize = 32;
const BAKE_SAMPLES: f64 = 2048.0 * 128.0;
/// Bake probes per axis the spline is fitted to.
const FIT_GRID: usize = 64;

/// A probe's n.v and roughness, and the lobe's (Fresnel scale, bias) there.
#[derive(Clone, Copy, Debug)]
struct Probe {
    n_dot_v: f64,
    roughness: f64,
    energy: [f64; 2],
}

impl Probe {
    /// The single-scatter albedo at F = 1, what the gain divides by.
    fn albedo(&self) -> f64 {
        self.energy[0] + self.energy[1]
    }
}

/// The checked-in fit, for the test that the generator writes exactly it.
const FIT_TEXT: &str = include_str!("../../../shaders/common/brdf_energy_fit.slang");

/// The uniform cubic B-spline, nonzero on (-2, 2), which the least-squares fit spans.
fn cubic_basis(x: f64) -> f64 {
    let t = x.abs();
    if t < 1.0 {
        2.0 / 3.0 - t * t + 0.5 * t * t * t
    } else if t < 2.0 {
        (2.0 - t).powi(3) / 6.0
    } else {
        0.0
    }
}

/// The spline as the whole tensor product of all `size` x `size` basis functions, the reference for the cell form.
fn tensor_spline(size: usize, coefficients: &[[f64; 2]], t: [f64; 2]) -> [f64; 2] {
    let x = t.map(|c| c * (size - 3) as f64 + 1.0);
    let mut out = [0.0; 2];
    for (i, row) in coefficients.chunks(size).enumerate() {
        let weight = cubic_basis(x[0] - i as f64);
        for (j, c) in row.iter().enumerate() {
            let w = weight * cubic_basis(x[1] - j as f64);
            out[0] += c[0] * w;
            out[1] += c[1] * w;
        }
    }
    out
}

/// `ggx_energy_fit` for `coefficients`, as this test writes the module.
fn fit_source(size: usize, coefficients: &[[f64; 2]]) -> String {
    let cells = size - 3;
    let mut lines = vec![
        "// Generated by crates/webgpu_renderer/tests/brdf_energy.rs from tests/brdf_energy_bake.slang: \
         KATAGLYPHIS_UPDATE_BRDF_ENERGY=1 rewrites it, then regenerate the WGSL and \
         python3 scripts/generate-shader-vectors.py."
            .to_owned(),
        String::new(),
        format!(
            "// The {size} x {size} least-squares cubic B-spline through ggx_energy at coordinates t in [0, 1]: \
             (Fresnel scale, bias), row by row of the first coordinate's basis."
        ),
        format!("static const float2 GGX_ENERGY_COEFFICIENTS[{}] = {{", size * size),
    ];
    let entries: Vec<String> = coefficients
        .iter()
        .map(|[s, b]| format!("float2({s:.7}, {b:.7})"))
        .collect();
    lines.extend(entries.chunks(3).map(|c| format!("    {},", c.join(", "))));
    lines.extend([
        "};".to_owned(),
        String::new(),
        "// The uniform cubic B-spline's four weights in a cell, at fraction f of it.".to_owned(),
        "float4 ggx_energy_weights(float f)".to_owned(),
        "{".to_owned(),
        "    float g = 1.0 - f;".to_owned(),
        "    return float4(g * g * g, 4.0 - 6.0 * f * f + 3.0 * f * f * f, 4.0 - 6.0 * g * g + 3.0 * g * g * g, \
         f * f * f) / 6.0;"
            .to_owned(),
        "}".to_owned(),
        String::new(),
        "// Only the 4 x 4 basis functions nonzero at t: the whole tensor product cost each call site every \
         term."
            .to_owned(),
        "float2 ggx_energy_fit(float2 t)".to_owned(),
        "{".to_owned(),
        format!("    float2 x = t * {cells}.0 + 1.0;"),
        "    // t = 1 is the last cell's far edge, not a cell past it.".to_owned(),
        format!("    float2 cell = clamp(floor(x), 1.0, {cells}.0);"),
        "    float4 wi = ggx_energy_weights(x.x - cell.x);".to_owned(),
        "    float4 wj = ggx_energy_weights(x.y - cell.y);".to_owned(),
        format!("    int first = int(cell.x - 1.0) * {size} + int(cell.y - 1.0);"),
        "    float2 e = float2(0.0);".to_owned(),
        "    for (int i = 0; i < 4; i++)".to_owned(),
        "    {".to_owned(),
        "        float2 row = float2(0.0);".to_owned(),
        "        for (int j = 0; j < 4; j++)".to_owned(),
        format!("            row += GGX_ENERGY_COEFFICIENTS[first + i * {size} + j] * wj[j];"),
        "        e += row * wi[i];".to_owned(),
        "    }".to_owned(),
        "    return e;".to_owned(),
        "}".to_owned(),
        String::new(),
    ]);
    lines.join("\n")
}

/// Solves the symmetric positive definite `a` (row by row, `n` x `n`) for each column of `b` (`n` x `m`).
fn cholesky_solve(mut a: Vec<f64>, n: usize, mut b: Vec<f64>, m: usize) -> Vec<f64> {
    for j in 0..n {
        for k in 0..j {
            for i in j..n {
                a[i * n + j] -= a[i * n + k] * a[j * n + k];
            }
        }
        let pivot = a[j * n + j].sqrt();
        for i in j..n {
            a[i * n + j] /= pivot;
        }
    }
    for col in 0..m {
        for i in 0..n {
            let sum: f64 = (0..i).map(|k| a[i * n + k] * b[k * m + col]).sum();
            b[i * m + col] = (b[i * m + col] - sum) / a[i * n + i];
        }
        for i in (0..n).rev() {
            let sum: f64 = (i + 1..n).map(|k| a[k * n + i] * b[k * m + col]).sum();
            b[i * m + col] = (b[i * m + col] - sum) / a[i * n + i];
        }
    }
    b
}

/// The `size` x `size` spline least-squares closest to `samples`, a `grid` x `grid` bake at `fit_probes(grid)`.
fn least_squares(samples: &[Probe], grid: usize, size: usize) -> Vec<[f64; 2]> {
    let t = |a: usize| a as f64 / (grid - 1) as f64;
    let basis: Vec<f64> = (0..grid)
        .flat_map(|a| {
            (0..size).map(move |k| cubic_basis(t(a) * (size - 3) as f64 + 1.0 - k as f64))
        })
        .collect();
    // The fit is separable: C = P Z P^T, with P = (B^T B)^-1 B^T for the basis matrix B of either axis.
    let gram: Vec<f64> = (0..size * size)
        .map(|e| {
            (0..grid)
                .map(|a| basis[a * size + e / size] * basis[a * size + e % size])
                .sum()
        })
        .collect();
    let transposed: Vec<f64> = (0..size * grid)
        .map(|e| basis[(e % grid) * size + e / grid])
        .collect();
    let p = cholesky_solve(gram, size, transposed, grid);
    let channel = |c: usize| {
        let z = |a: usize, b: usize| samples[a * grid + b].energy[c];
        let y: Vec<f64> = (0..grid * size)
            .map(|e| {
                (0..grid)
                    .map(|b| z(e / size, b) * p[(e % size) * grid + b])
                    .sum()
            })
            .collect();
        (0..size * size)
            .map(|e| {
                (0..grid)
                    .map(|a| p[(e / size) * grid + a] * y[a * size + e % size])
                    .sum()
            })
            .collect::<Vec<f64>>()
    };
    let (scale, bias) = (channel(0), channel(1));
    scale.into_iter().zip(bias).map(|(s, b)| [s, b]).collect()
}

/// `entry` of brdf_energy_bake.wgsl over fit coordinates, `per_probe` invocations each.
fn dispatch(gpu: &GpuContext, entry: &str, probes: &[[f32; 2]], per_probe: usize) -> Vec<[f32; 4]> {
    let device = &gpu.device;
    let module = device.create_shader_module(wgpu::ShaderModuleDescriptor {
        label: Some("brdf_energy"),
        source: wgpu::ShaderSource::Wgsl(BAKE_WGSL.into()),
    });
    let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
        label: Some(entry),
        layout: None,
        module: &module,
        entry_point: Some(entry),
        compilation_options: Default::default(),
        cache: None,
    });
    let input = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
        label: Some("brdf_energy_probes"),
        contents: bytemuck::cast_slice(probes),
        usage: wgpu::BufferUsages::STORAGE,
    });
    let invocations = probes.len() * per_probe;
    let bytes = (invocations * 16) as u64;
    let output = device.create_buffer(&wgpu::BufferDescriptor {
        label: Some("brdf_energy_results"),
        size: bytes,
        usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
        mapped_at_creation: false,
    });
    let readback = device.create_buffer(&wgpu::BufferDescriptor {
        label: Some("brdf_energy_readback"),
        size: bytes,
        usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
        mapped_at_creation: false,
    });
    let bind_group = device.create_bind_group(&wgpu::BindGroupDescriptor {
        label: Some("brdf_energy"),
        layout: &pipeline.get_bind_group_layout(0),
        entries: &[
            wgpu::BindGroupEntry {
                binding: 0,
                resource: input.as_entire_binding(),
            },
            wgpu::BindGroupEntry {
                binding: 1,
                resource: output.as_entire_binding(),
            },
        ],
    });
    let mut encoder = device.create_command_encoder(&wgpu::CommandEncoderDescriptor::default());
    {
        let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor::default());
        pass.set_pipeline(&pipeline);
        pass.set_bind_group(0, &bind_group, &[]);
        pass.dispatch_workgroups((invocations as u32).div_ceil(64), 1, 1);
    }
    encoder.copy_buffer_to_buffer(&output, 0, &readback, 0, bytes);
    gpu.queue.submit(Some(encoder.finish()));
    readback.slice(..).map_async(wgpu::MapMode::Read, |result| {
        result.expect("readback must map")
    });
    device
        .poll(wgpu::PollType::wait_indefinitely())
        .expect("poll must succeed");
    let data = readback.slice(..).get_mapped_range().expect("mapped");
    bytemuck::pod_collect_to_vec(&data)
}

/// `cs_bake` at `probes`: each probe's chunks summed in f64.
fn bake(gpu: &GpuContext, probes: &[[f32; 2]]) -> Vec<Probe> {
    dispatch(gpu, "cs_bake", probes, BAKE_CHUNKS)
        .chunks(BAKE_CHUNKS)
        .map(|chunks| {
            let sum = |c: usize| chunks.iter().map(|r| f64::from(r[c])).sum::<f64>() / BAKE_SAMPLES;
            Probe {
                n_dot_v: f64::from(chunks[0][2]),
                roughness: f64::from(chunks[0][3]),
                energy: [sum(0), sum(1)],
            }
        })
        .collect()
}

/// `cs_lookup` at `probes`: `ggx_energy` as every shader evaluates the fit.
fn lookup(gpu: &GpuContext, probes: &[[f32; 2]]) -> Vec<Probe> {
    dispatch(gpu, "cs_lookup", probes, 1)
        .iter()
        .map(|r| Probe {
            n_dot_v: f64::from(r[2]),
            roughness: f64::from(r[3]),
            energy: [f64::from(r[0]), f64::from(r[1])],
        })
        .collect()
}

/// BeschleunigerBallett's `white_single_scatter_albedo` specular half (`GoldenMetrics.hpp`) in f64, split by Fresnel.
fn quadrature(mu: f64, roughness: f64) -> [f64; 2] {
    const ROWS: usize = 2048;
    const COLUMNS: usize = 128;
    let floored = roughness.max(0.045);
    let a2 = floored.powi(4);
    let k = floored * floored / 2.0;
    let g1 = |c: f64| c / (c * (1.0 - k) + k).max(1e-6);
    let v = DVec3::new((1.0 - mu * mu).max(0.0).sqrt(), 0.0, mu);
    let n_dot_v = mu.max(1e-4);
    let mut sum = [0.0; 2];
    for i in 0..ROWS {
        let xi = (i as f64 + 0.5) / ROWS as f64;
        let n_dot_h = ((1.0 - xi) / (1.0 + (a2 - 1.0) * xi)).sqrt();
        let sin_h = (1.0 - n_dot_h * n_dot_h).max(0.0).sqrt();
        let d = n_dot_h * n_dot_h * (a2 - 1.0) + 1.0;
        let density = a2 / (PI * d * d) * n_dot_h;
        let ndf = a2 / (PI * (d * d).max(1e-20));
        for j in 0..COLUMNS {
            let phi = (j as f64 + 0.5) / COLUMNS as f64 * 2.0 * PI;
            let h = DVec3::new(sin_h * phi.cos(), sin_h * phi.sin(), n_dot_h);
            let v_dot_h = v.dot(h);
            let n_dot_l = 2.0 * v_dot_h * n_dot_h - v.z;
            if v_dot_h <= 0.0 || n_dot_l <= 0.0 {
                continue;
            }
            let f = ndf * g1(n_dot_v) * g1(n_dot_l) / (4.0 * n_dot_v * n_dot_l).max(1e-6);
            let weight = f * n_dot_l * 4.0 * v_dot_h / density;
            let fc = (1.0 - v_dot_h).clamp(0.0, 1.0).powi(5);
            sum[0] += weight * (1.0 - fc);
            sum[1] += weight * fc;
        }
    }
    sum.map(|s| s / (ROWS * COLUMNS) as f64)
}

/// Fit coordinates of a `grid` x `grid` lattice over [0, 1], ends included, row by row.
fn fit_probes(grid: usize) -> Vec<[f32; 2]> {
    let t = |a: usize| a as f32 / (grid - 1) as f32;
    (0..grid)
        .flat_map(|a| (0..grid).map(move |b| [t(a), t(b)]))
        .collect()
}

#[test]
fn the_quadrature_reproduces_the_furnace_goldens_table() {
    // BeschleunigerBallett's path-tracing.md: E(mu) of a white metal with brdf_sampled's lobe.
    for (roughness, mu, expected) in [
        (0.3, 1.0, 0.9876),
        (0.3, 0.5, 0.9012),
        (0.7, 1.0, 0.6710),
        (0.7, 0.5, 0.6123),
    ] {
        let [scale, bias] = quadrature(mu, roughness);
        assert!(
            (scale + bias - expected).abs() < 2e-4,
            "roughness {roughness}, mu {mu}: {} against the golden's {expected}",
            scale + bias
        );
    }
}

#[test]
fn the_checked_in_fit_is_fitted_to_a_fresh_bake_of_brdf_slangs_lobe() {
    let Some(gpu) = GpuContext::headless_or_skip() else {
        return;
    };
    let (size, checked_in) = common::fit();
    let size = *size;
    let probes = fit_probes(FIT_GRID);
    let baked = bake(&gpu, &probes);
    let fresh = least_squares(&baked, FIT_GRID, size);
    if std::env::var_os("KATAGLYPHIS_UPDATE_BRDF_ENERGY").is_some() {
        std::fs::write(FIT_PATH, fit_source(size, &fresh)).expect("writes the fit");
        eprintln!(
            "refitted brdf_energy_fit.slang; regenerate the WGSL with compile-slang-shaders.sh and the vectors with \
             python3 scripts/generate-shader-vectors.py"
        );
        return;
    }
    // The grazing f32 bake varies by adapter (WARP: 3.78e-3); a stale fit shows above n.v 0.01.
    for (min, max, bound) in [(0.01, f64::INFINITY, 3e-4), (0.0, 0.01, 5e-3)] {
        let (worst, at) = probes
            .iter()
            .enumerate()
            .filter(|&(i, _)| (min..max).contains(&baked[i].n_dot_v))
            .map(|(i, t)| {
                let t = t.map(f64::from);
                let (a, b) = (
                    common::spline(size, &fresh, t),
                    common::spline(size, checked_in, t),
                );
                (i, (a[0] - b[0]).abs().max((a[1] - b[1]).abs()))
            })
            .fold(
                (0.0, 0),
                |best, (i, d)| if d > best.0 { (d, i) } else { best },
            );
        eprintln!(
            "n.v in [{min}, {max}): checked-in fit against a fresh one: max difference {worst:.2e} at n.v {:.5}, \
             roughness {:.4}",
            baked[at].n_dot_v, baked[at].roughness
        );
        assert!(
            worst < bound,
            "brdf_energy_fit.slang is stale for n.v in [{min}, {max}) (max difference {worst:.2e}, bound \
             {bound:.0e}): KATAGLYPHIS_UPDATE_BRDF_ENERGY=1 refits it"
        );
    }
    // The bake is the goldens' quadrature, from the narrowest grazing lobe to the roughest head-on one.
    for &(a, b) in &[(0, 0), (3, 0), (10, 5), (40, 40), (63, 25), (63, 63)] {
        let probe = baked[a * FIT_GRID + b];
        let [scale, bias] = quadrature(probe.n_dot_v, probe.roughness);
        let bound = if probe.n_dot_v < 0.01 { 5e-3 } else { 2e-4 };
        assert!(
            (probe.energy[0] - scale).abs() < bound && (probe.energy[1] - bias).abs() < bound,
            "the bake at n.v {}, roughness {} is {:?}, the quadrature ({scale}, {bias})",
            probe.n_dot_v,
            probe.roughness,
            probe.energy
        );
    }
}

/// Worst relative albedo and absolute bias error of `fit` against `exact`, over the probes with n.v at least `min`.
fn worst_error(exact: &[Probe], fit: &[Probe], min: f64) -> (f64, f64) {
    exact
        .iter()
        .zip(fit)
        .filter(|(e, _)| e.n_dot_v >= min)
        .fold((0.0, 0.0), |(albedo, bias), (e, t)| {
            (
                albedo.max((t.albedo() / e.albedo() - 1.0).abs()),
                bias.max((t.energy[1] - e.energy[1]).abs()),
            )
        })
}

/// Between the fitted probes, where a spline strays furthest: the bake and the fit at every lattice cell's centre.
#[test]
fn the_fit_matches_the_lobe_within_its_measured_error() {
    let Some(gpu) = GpuContext::headless_or_skip() else {
        return;
    };
    let centres: Vec<[f32; 2]> = fit_probes(FIT_GRID - 1)
        .iter()
        .map(|t| t.map(|c| (c * (FIT_GRID - 2) as f32 + 0.5) / (FIT_GRID - 1) as f32))
        .collect();
    let exact = bake(&gpu, &centres);
    let fit = lookup(&gpu, &centres);
    // The tests' CPU mirror evaluates the fit as the shaders do, so their analytic references take the same gain.
    for probe in &fit {
        let cpu = common::ggx_energy(probe.n_dot_v, probe.roughness);
        assert!(
            (cpu[0] - probe.energy[0]).abs() < 1e-5 && (cpu[1] - probe.energy[1]).abs() < 1e-5,
            "the CPU mirror reads {cpu:?} at n.v {}, roughness {}, ggx_energy {:?}",
            probe.n_dot_v,
            probe.roughness,
            probe.energy
        );
    }
    // Worst on lavapipe: 0.0138/0.0098, 0.0056/0.0047, 0.0013/0.0012, 0.0004/0.0003; WARP: 0.0174/0.0125.
    let bands = [
        (0.0, 0.019, 0.014),
        (0.01, 0.007, 0.006),
        (0.05, 0.0017, 0.0016),
        (0.2, 0.0006, 0.0005),
    ];
    let measured: Vec<(f64, f64)> = bands
        .iter()
        .map(|&(min, ..)| worst_error(&exact, &fit, min))
        .collect();
    for (&(min, ..), &(albedo, bias)) in bands.iter().zip(&measured) {
        eprintln!("n.v >= {min}: worst albedo error {albedo:.4} (relative), bias {bias:.4}");
    }
    for (&(min, albedo_bound, bias_bound), &(albedo, bias)) in bands.iter().zip(&measured) {
        assert!(
            albedo < albedo_bound && bias < bias_bound,
            "the fit misses the lobe at n.v >= {min}: albedo {albedo:.4}, bias {bias:.4}"
        );
    }
}

/// The diffuse lobe takes 1 - E_spec, so the compensated lobe must never return much more than it receives.
#[test]
fn the_compensated_lobe_never_returns_more_than_it_receives() {
    let (size, coefficients) = common::fit();
    for t in fit_probes(FIT_GRID) {
        let energy = common::spline(*size, coefficients, t.map(f64::from));
        // A fit may pass the lobe's albedo of 1 by its own error, which saturate() keeps out of the diffuse share.
        assert!(
            energy[1] <= energy[0] + energy[1] + 1e-4 && energy[0] + energy[1] <= 1.002,
            "the fit's scale and bias {energy:?} at {t:?} pass the lobe's whole albedo"
        );
        for f0 in [0.0, 0.04, 0.5, 1.0] {
            let albedo = common::specular_albedo(energy, f0);
            assert!(albedo <= 1.002, "E_spec {albedo} at f0 {f0}, {t:?}");
        }
        // Turquin's gain completes a white metal's lobe exactly.
        assert!((common::specular_albedo(energy, 1.0) - 1.0).abs() < 1e-9);
        assert!(common::multiscatter_gain(energy, 1.0) >= 0.998);
    }
}

#[test]
fn the_checked_in_fit_is_what_the_generator_writes() {
    let (size, coefficients) = common::fit();
    assert_eq!(
        fit_source(*size, coefficients),
        FIT_TEXT,
        "brdf_energy_fit.slang differs from fit_source's output for its own coefficients"
    );
}

#[test]
fn the_cell_evaluation_is_the_whole_tensor_product() {
    let (size, coefficients) = common::fit();
    // Every knot, both edges and the points between: the cell index changes exactly on the knots.
    let steps = 11 * 40;
    let mut worst = 0.0f64;
    for a in 0..=steps {
        for b in 0..=steps {
            let t = [a as f64 / steps as f64, b as f64 / steps as f64];
            let (cell, full) = (
                common::spline(*size, coefficients, t),
                tensor_spline(*size, coefficients, t),
            );
            worst = worst.max((cell[0] - full[0]).abs().max((cell[1] - full[1]).abs()));
        }
    }
    assert!(
        worst < 1e-12,
        "the 4 x 4 cell evaluation departs from the full tensor product by {worst:e}"
    );
}
